import pickle
from pathlib import Path

import streamlit as st

st.set_page_config(page_title="SMS Spam Detector", page_icon="📩", layout="centered")

MODEL_PATH = Path(__file__).parent / "model.pkl"

@st.cache_resource
def load_model():
    with MODEL_PATH.open("rb") as file:
        return pickle.load(file)

st.title("📩 SMS Spam Detector")
st.write("Enter an SMS message below to classify it as **Spam** or **Ham (Legitimate)**.")
st.divider()

message = st.text_area("Your message", placeholder="Type or paste an SMS message here...", height=140)

if st.button("Predict Message", type="primary", use_container_width=True):
    if not message.strip():
        st.warning("Please enter a message before predicting.")
    else:
        try:
            model = load_model()
            prediction = model.predict([message.strip()])[0]
            label = str(prediction).lower()

            if label == "spam":
                st.error("🚨 This message appears to be SPAM.")
            else:
                st.success("✅ This message appears to be HAM (legitimate).")
            st.caption("This prediction is generated by a machine-learning model and may not always be correct.")
        except Exception as error:
            st.error("Unable to make a prediction. Please check that the model file is valid and compatible.")
            st.exception(error)
